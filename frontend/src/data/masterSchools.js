// Master helper search utility
export const searchMasterSchoolsLocal = (query = '', districtFilter = 'all', limit = 20) => {
  const cleanQ = query.trim().toLowerCase();
  
  return MASTER_SCHOOLS.filter(s => {
    const matchesDistrict = districtFilter === 'all' || s.district.toLowerCase() === districtFilter.toLowerCase();
    if (!cleanQ) return matchesDistrict;

    const matchesName = s.school_name.toLowerCase().includes(cleanQ);
    const matchesBlock = s.block_or_cluster.toLowerCase().includes(cleanQ);
    const matchesArea = s.area.toLowerCase().includes(cleanQ);
    const matchesDist = s.district.toLowerCase().includes(cleanQ);
    const matchesBoard = s.board.toLowerCase().includes(cleanQ);

    return matchesDistrict && (matchesName || matchesBlock || matchesArea || matchesDist || matchesBoard);
  }).slice(0, limit);
};

export const getMasterSchoolById = (id) => {
  return MASTER_SCHOOLS.find(s => s.id === id) || null;
};
